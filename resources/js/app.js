/**
 * Meng-escape teks sebelum dimasukkan ke innerHTML.
 *
 * Dipakai bersama oleh pencarian global di layout dan pengelola berkas di
 * halaman detail CRMC. Diletakkan di sini supaya tersedia di semua halaman,
 * bukan hanya halaman yang kebetulan mendefinisikannya.
 */
window.escapeHtml = function (value) {
    return String(value).replace(/[&<>"']/g, (character) => ({
        '&': '&amp;',
        '<': '&lt;',
        '>': '&gt;',
        '"': '&quot;',
        "'": '&#039;',
    }[character]));
};
